/**
 * تطبيع الاسم العربي للمقارنة والبحث:
 * يزيل التشكيل والتطويل، ويوحّد الهمزات والياء والتاء المربوطة، ويحذف الرموز.
 * "أحمد الإبراهيمي" و"احمد الابراهيمي" تعطيان المفتاح نفسه.
 */
export function nameKey(value) {
  return String(value || '')
    .normalize('NFC')
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
    .replace(/[\u0622\u0623\u0625\u0671]/g, 'ا')
    .replace(/\u0649/g, 'ي')
    .replace(/\u0629/g, 'ه')
    .replace(/[\u0624\u0626]/g, 'ء')
    .replace(/[^\u0621-\u064Aa-zA-Z0-9\s]/g, ' ')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();
}
